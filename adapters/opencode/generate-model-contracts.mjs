// Build the model protocol from the service's executable structural declaration, not handwritten
// JSON approximations or a source-code parser. Run Gradle generateModelContracts first.
import {readFile,writeFile} from "node:fs/promises"
import path from "node:path"
const source=process.env.WRITHELM_MODEL_PROTOCOL??"../../backend/server/build/generated/model-contracts/writhelm/model-knowledge-v1.json"
const raw=await readFile(source,"utf8"),value=JSON.parse(raw)
if(value.formatVersion!==1||!value.commands||!value.reads)throw Error("Unsupported generated model contract")
const expected="// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by generate-model-contracts.mjs from KnowledgeProtocol.kt. Do not edit.\nexport default "+JSON.stringify(value)+" as const\n"
const work=JSON.parse(await readFile(path.join(path.dirname(source),"model-work-export-v1.json"),"utf8"))
const expectedWork="// SPDX-License-Identifier: AGPL-3.0-only\n// Generated from packaged authoritative WorkProtocol resource. Do not edit.\nexport default "+JSON.stringify(work)+" as const\n"
if(process.argv.includes("--check")){
  if(await readFile("src/generated/model-knowledge.ts","utf8")!==expected||
     await readFile("src/generated/model-work.ts","utf8")!==expectedWork)throw Error("Generated model contract is stale; regenerate from current service declaration")
  console.log("Generated model contract matches current service declaration: PASS")
}else{
  await writeFile("src/generated/model-knowledge.ts",expected)
  await writeFile("src/generated/model-work.ts",expectedWork)
}
